import Foundation
import CleanRoomCore

func runIgnoreIntegrationChecks() throws {
    let s = CoreTests(); try s.setUpWithError(); defer { try? s.tearDownWithError() }
    let excluded = try s.write("private/keep.txt", Data("private".utf8))
    let neighbor = try s.write("private-other/visible.txt", Data("visible".utf8))
    let ordinary = try s.write("ordinary.txt", Data("ordinary".utf8))
    let store = IgnoreRuleStore(home: s.home)
    let old = s.report(.downloads)
    let parent = try unwrap(old.items.first { $0.path == excluded.deletingLastPathComponent().path })
    checkTrue(parent.canTrash)
    try store.save([excluded.path])
    let blocked = s.manager().trash([parent])
    checkTrue(blocked.records.isEmpty); checkTrue(blocked.errors.contains { $0.contains("忽略") })
    checkTrue(s.fm.fileExists(atPath: excluded.path))
    let listing = s.report(.downloads)
    let protectedParent = try unwrap(listing.items.first { $0.path == parent.path })
    checkFalse(protectedParent.canTrash)
    let files = s.report(.largeFiles)
    checkFalse(files.items.contains { $0.path == excluded.path })
    checkTrue(files.items.contains { $0.path == neighbor.path })
    checkTrue(files.items.contains { $0.path == ordinary.path })
    try store.save([excluded.deletingLastPathComponent().path])
    let nested = s.report(.largeFiles)
    checkFalse(nested.items.contains { $0.path == excluded.path })
    checkTrue(nested.items.contains { $0.path == neighbor.path })
    let rootIgnored = Scanner().scan(.duplicates, options: ScanOptions(home: s.home, roots: [s.files], excludedPaths: [s.files.path]))
    checkTrue(rootIgnored.items.isEmpty); checkEqual(rootIgnored.visitedFiles, 0)
    let advancedRoot = s.home.appendingPathComponent("Library/Developer/Xcode/DerivedData")
    let advancedIgnored = try s.write("project/keep", under: advancedRoot)
    try store.save([advancedIgnored.path])
    let advanced = ExtendedCleanupScanner().scan(.developerCaches, options: .init(home: s.home))
    let protectedAdvanced = try unwrap(advanced.items.first { $0.path == advancedIgnored.deletingLastPathComponent().path })
    checkFalse(protectedAdvanced.canTrash)
    try Data("invalid json".utf8).write(to: store.fileURL)
    let corrupt = s.report(.downloads)
    checkTrue(corrupt.truncated); checkTrue(corrupt.items.isEmpty)
    let refused = s.manager().trash([try unwrap(old.items.first { $0.path == ordinary.path })])
    checkTrue(refused.records.isEmpty); checkTrue(s.fm.fileExists(atPath: ordinary.path))
}
